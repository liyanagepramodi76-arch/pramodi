function changeLanguage(language, button) {

    const selectedLanguage = translations[language];

    if (!selectedLanguage) {
        return;
    }

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.getAttribute("data-i18n");

        if (selectedLanguage[key]) {
            element.textContent = selectedLanguage[key];
        }

    });

    document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.classList.remove("active");
    });

    if (button) {
        button.classList.add("active");
    }

    localStorage.setItem("rubberlinkLanguage", language);
}


document.addEventListener("DOMContentLoaded", function () {

    const savedLanguage =
        localStorage.getItem("rubberlinkLanguage") || "en";

    const button =
        document.querySelector(`.lang-btn[onclick*="'${savedLanguage}'"]`);

    changeLanguage(savedLanguage, button);

});